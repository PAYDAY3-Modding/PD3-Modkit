[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
try {
    $pluginDirectory = Split-Path -Parent $PSScriptRoot
    $sourceDirectory = Join-Path $pluginDirectory 'NativeClasses'
    $outputDirectory = Join-Path $pluginDirectory 'Intermediate/NativeBodies'
    $outputFile = Join-Path $outputDirectory 'SuzieNativeBodies.generated.inl'
    $lines = [System.Collections.Generic.List[string]]::new()
    $registrations = [System.Collections.Generic.List[string]]::new()
    $seen = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    $lines.Add('// Generated by Suzie. Edit NativeClasses/<Module>/<Class>.cpp instead.')

    # Mask comments, strings (including raw strings) and character literals without changing offsets.
    $tokens = [regex]::new('(?s)R"(?<delimiter>[^\s()\\]{0,16})\(.*?\)\k<delimiter>"|/\*.*?\*/|//[^\r\n]*|"(?:\\.|[^"\\])*"|''(?:\\.|[^''\\])*''')
    $declaration = [regex]::new('\bSUZIE_FUNCTION\s*\(\s*(?<class>[A-Za-z_]\w*)\s*,\s*(?<function>[A-Za-z_]\w*)\s*\)\s*\{')
    $access = [regex]::new('\bContext\s*\.\s*(?<operation>GetParam|SetParam|GetProperty|SetProperty|GetReturn|SetReturn)\s*<')
    $files = @()
    if (Test-Path -LiteralPath $sourceDirectory) {
        $files = @(Get-ChildItem -LiteralPath $sourceDirectory -Recurse -File -Filter '*.cpp' | Sort-Object FullName)
    }
    foreach ($file in $files) {
        $relative = $file.FullName.Substring($sourceDirectory.Length).TrimStart('\', '/') -replace '\\', '/'
        if ($relative -notmatch '^(?<module>[A-Za-z_]\w*)/(?<class>[A-Za-z_]\w*)\.cpp$') {
            throw "$relative : expected NativeClasses/<Module>/<Class>.cpp"
        }
        $module = $Matches.module
        $class = $Matches.class
        $text = [IO.File]::ReadAllText($file.FullName)
        $masked = $tokens.Replace($text, [System.Text.RegularExpressions.MatchEvaluator]{ param($m) [regex]::Replace($m.Value, '[^\r\n]', ' ') })
        $functions = @($declaration.Matches($masked))
        # Every macro token must be a valid definition; catch typos rather than silently omitting a body.
        if ([regex]::Matches($masked, '\bSUZIE_FUNCTION\b').Count -ne $functions.Count) {
            throw "$relative : use SUZIE_FUNCTION(ClassName, FunctionName) { ... }"
        }
        $prefix = "SuzieBody_$($module.Length)_${module}_$($class.Length)_${class}"
        $lines.Add("#define SUZIE_FUNCTION(Class, Function) static void ${prefix}_Function_##Function(FSuzieFunctionContext& Context)")
        $lines.Add("#define SUZIE_CONSTRUCT(Class) static void ${prefix}_Callback_Construct(FSuzieFunctionContext& Context)")
        $lines.Add('#define SUZIE_CONSTRUCTOR(Class) SUZIE_CONSTRUCT(Class)')
        $lines.Add("#define SUZIE_POST_INITIALIZE(Class) static void ${prefix}_Callback_PostInitialize(FSuzieFunctionContext& Context)")
        $lines.Add("#define SUZIE_PROPERTY_CHANGED(Class, Property) static void ${prefix}_Callback_PropertyChanged_##Property(FSuzieFunctionContext& Context)")
        $lines.Add("#define SUZIE_REFRESH(Class) static void ${prefix}_Callback_Refresh(FSuzieFunctionContext& Context)")
        $include = $file.FullName.Replace('\', '/')
        $lines.Add("#include `"$include`"")
        $lines.Add('#undef SUZIE_FUNCTION')
        $lines.Add('#undef SUZIE_CONSTRUCTOR')
        $lines.Add('#undef SUZIE_CONSTRUCT')
        $lines.Add('#undef SUZIE_POST_INITIALIZE')
        $lines.Add('#undef SUZIE_PROPERTY_CHANGED')
        $lines.Add('#undef SUZIE_REFRESH')
        if ($masked -match '\bSUZIE_NATIVE_ADAPTER\b') { throw "$relative : native adapter declarations are unsupported; use lifecycle/property/refresh callbacks" }
        $lifecyclePattern = '\b(?<macro>SUZIE_CONSTRUCT|SUZIE_CONSTRUCTOR|SUZIE_POST_INITIALIZE|SUZIE_REFRESH|SUZIE_PROPERTY_CHANGED)\s*\(\s*(?<class>[A-Za-z_]\w*)\s*(?:,\s*(?<property>[A-Za-z_]\w*)\s*)?\)\s*\{'
        $callbacks = @([regex]::Matches($masked, $lifecyclePattern))
        if ([regex]::Matches($masked, '\b(?:SUZIE_CONSTRUCT|SUZIE_CONSTRUCTOR|SUZIE_POST_INITIALIZE|SUZIE_PROPERTY_CHANGED|SUZIE_REFRESH)\b').Count -ne $callbacks.Count) {
            throw "$relative : malformed lifecycle callback declaration"
        }
        foreach ($callback in $callbacks) {
            if ($callback.Groups['class'].Value -cne $class) { throw "$relative : callback class must match filename ($class)" }
            $cursor = $callback.Index + $callback.Length
            $depth = 1
            while ($cursor -lt $masked.Length -and $depth -gt 0) {
                if ($masked[$cursor] -eq '{') { $depth++ }
                if ($masked[$cursor] -eq '}') { $depth-- }
                $cursor++
            }
            if ($depth -ne 0) { throw "$relative : unclosed lifecycle callback body" }
            $macro = $callback.Groups['macro'].Value
            $property = $callback.Groups['property'].Value
            $phase = switch ($macro) {
                'SUZIE_POST_INITIALIZE' { 'PostInitialize' }
                'SUZIE_PROPERTY_CHANGED' { 'PropertyChanged' }
                'SUZIE_REFRESH' { 'Refresh' }
                default { 'Construct' }
            }
            if (($phase -eq 'PropertyChanged') -ne ($property.Length -gt 0)) { throw "$relative : only SUZIE_PROPERTY_CHANGED takes a property name" }
            if (!$seen.Add("/Script/${module}.${class}@$phase/$property")) { throw "$relative : duplicate $macro callback for $property" }
            $suffix = if ($property) { "${phase}_$property" } else { $phase }
            $propertyArg = if ($property) { "TEXT(`"$property`")" } else { 'NAME_None' }
            $registrations.Add("SuzieNativeLifecycle::Register(TEXT(`"/Script/${module}.${class}`"), ESuzieCallbackPhase::$phase, $propertyArg, &${prefix}_Callback_$suffix, TEXT(`"$relative`"));")
        }
        foreach ($function in $functions) {
            $name = $function.Groups['function'].Value
            $path = "/Script/${module}.${class}:$name"
            if ($function.Groups['class'].Value -cne $class) { throw "$relative : macro class must match filename ($class)" }
            if (!$seen.Add($path)) { throw "$relative : duplicate implementation $path" }
            $start = $function.Index + $function.Length
            $end = $start
            $depth = 1
            while ($end -lt $masked.Length -and $depth -gt 0) {
                if ($masked[$end] -eq '{') { $depth++ }
                if ($masked[$end] -eq '}') { $depth-- }
                $end++
            }
            if ($depth -ne 0) { throw "$relative : unclosed body for $name" }
            $bodyMask = $masked.Substring($start, $end - $start - 1)
            $bodyText = $text.Substring($start, $end - $start - 1)
            $symbol = "${prefix}_Function_$name"
            $lines.Add("static bool ${symbol}_Validate(UFunction& Function, FString& Error) {")
            # Preflight literal typed Context accesses before binding. Dynamic names and accesses
            # through reflection views are always validated by the API at the point of use.
            foreach ($call in $access.Matches($bodyMask)) {
                # Locally declared C++ type names are not visible to an external validator.
                # The context still checks these accesses before reading/writing any memory.
                if ($bodyMask -match '\b(using|typedef|struct|class|enum)\b') { continue }
                $typeStart = $call.Index + $call.Length
                $cursor = $typeStart
                $angles = 1
                while ($cursor -lt $bodyMask.Length -and $angles -gt 0) {
                    if ($bodyMask[$cursor] -eq '<') { $angles++ }
                    if ($bodyMask[$cursor] -eq '>') { $angles-- }
                    $cursor++
                }
                if ($angles -ne 0) { throw "$relative : malformed Context template argument in $name" }
                $type = $bodyText.Substring($typeStart, $cursor - $typeStart - 1).Trim()
                $operation = $call.Groups['operation'].Value
                $scope = if ($operation.EndsWith('Return')) { 'Return' } elseif ($operation.EndsWith('Property')) { 'Property' } else { 'Param' }
                $parameter = 'ReturnValue'
                if ($scope -ne 'Return') {
                    $argument = [regex]::Match($bodyText.Substring($cursor), '^\s*\(\s*(?:TEXT\s*\(\s*)?"(?<name>[A-Za-z_]\w*)"')
                    if (!$argument.Success) { continue }
                    $parameter = $argument.Groups['name'].Value
                }
                $write = if ($operation.StartsWith('Set')) { 'true' } else { 'false' }
                $lines.Add("if (!SuzieNative::Expect<$type>(Function, SuzieNative::EScope::$scope, TEXT(`"$parameter`"), $write, Error)) { return false; }")
            }
            $lines.Add('return true; }')
            $lines.Add("static void ${symbol}_Thunk(UObject* Self, FFrame& Stack, RESULT_DECL) { SuzieNative::Invoke(TEXT(`"$path`"), Self, Stack, RESULT_PARAM); }")
            $registrations.Add("SuzieNative::Register(TEXT(`"$path`"), &${symbol}_Thunk, &$symbol, &${symbol}_Validate, TEXT(`"$relative`"));")
        }
    }
    $lines.Add('void RegisterGeneratedSuzieNativeFunctions() {')
    foreach ($registration in $registrations) { $lines.Add($registration) }
    $lines.Add('}')
    $output = ($lines -join "`n") + "`n"
    if (!(Test-Path -LiteralPath $outputDirectory)) { [IO.Directory]::CreateDirectory($outputDirectory) | Out-Null }
    if (!(Test-Path -LiteralPath $outputFile) -or [IO.File]::ReadAllText($outputFile) -cne $output) {
        # Replace atomically, retaining timestamps on no-op builds.
        $temporary = "$outputFile.$PID.tmp"
        [IO.File]::WriteAllText($temporary, $output, [Text.UTF8Encoding]::new($false))
        if (Test-Path -LiteralPath $outputFile) { [IO.File]::Replace($temporary, $outputFile, [NullString]::Value) }
        else { [IO.File]::Move($temporary, $outputFile) }
        Write-Host "Suzie: generated $($registrations.Count) native body registration(s)."
    }
} catch {
    [Console]::Error.WriteLine("Suzie native body generation failed: $_")
    exit 1
}
